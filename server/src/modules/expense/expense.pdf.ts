function drawCompactDetails(doc: PDFKit.PDFDocument, note: ExpensePdfNote, t: ExpensePdfLabels) {
  const left = pageLeft(doc);
  const width = pageWidth(doc);
  doc.font('Helvetica-Bold').fontSize(10.5).fillColor('#0f172a');
  doc.text(t.details, left, doc.y, { width });
  doc.y += 14;

  const top = doc.y;
  drawCard(doc, left, top, width, 82, '#ffffff', '#dbeafe');
  const rows: Array<[string, string]> = [
    [t.merchant, note.merchantName ?? '-'],
    [t.documentNumber, note.documentNumber ?? note.receiptNumber ?? '-'],
    [t.category, note.category?.name ?? '-'],
    [t.type, note.expenseType?.name ?? '-'],
    [t.date, formatDate(note.expenseDate)],
    [t.source, note.source],
  ];
  rows.forEach((row, index) => drawCompactMeta(doc, left + 14 + (index % 3) * 176, top + 12 + Math.floor(index / 3) * 32, row[0], row[1]));
  doc.y = top + 94;

  doc.font('Helvetica-Bold').fontSize(10.5).fillColor('#0f172a');
  doc.text(t.amount, left, doc.y, { width });
  doc.y += 14;
  const amountTop = doc.y;
  drawCard(doc, left, amountTop, width, 58, '#f8fafc', '#e2e8f0');
  drawCompactMeta(doc, left + 14, amountTop + 12, t.amountHT, formatCurrency(Number(note.amountHT ?? 0), note.currency));
  drawCompactMeta(doc, left + 146, amountTop + 12, t.vatRate, `${Number(note.vatRate).toFixed(2)}%`);
  drawCompactMeta(doc, left + 278, amountTop + 12, t.vatAmount, formatCurrency(Number(note.vatAmount), note.currency));
  drawCompactMeta(doc, left + 410, amountTop + 12, t.amountTTC, formatCurrency(Number(note.amountTTC), note.currency), true);
  doc.y = amountTop + 70;

  if (note.approvedBy || note.approvedAt || note.comment) {
    const approvalTop = doc.y;
    drawCard(doc, left, approvalTop, width, 50, '#ecfdf5', '#bbf7d0');
    drawCompactMeta(doc, left + 14, approvalTop + 10, t.approvedBy, note.approvedBy?.name ?? '-');
    drawCompactMeta(doc, left + 176, approvalTop + 10, t.approvedAt, note.approvedAt ? formatDateTime(note.approvedAt) : '-');
    drawCompactMeta(doc, left + 338, approvalTop + 10, t.comment, trimText(note.comment ?? '-', 52));
    doc.y = approvalTop + 60;
  }
}

function drawCompactAuditAndReceipt(doc: PDFKit.PDFDocument, note: ExpensePdfNote, t: ExpensePdfLabels) {
  const left = pageLeft(doc);
  const width = pageWidth(doc);
  const gap = 10;
  const auditWidth = Math.round(width * 0.48);
  const receiptWidth = width - auditWidth - gap;
  const top = doc.y;
  const blockHeight = 176;

  drawCard(doc, left, top, auditWidth, blockHeight, '#ffffff', '#e2e8f0');
  doc.font('Helvetica-Bold').fontSize(10).fillColor('#0f172a').text(t.audit, left + 12, top + 10, { width: auditWidth - 24 });
  const logs = (note.auditLogs ?? []).slice(-3);
  if (logs.length) {
    logs.forEach((log, index) => {
      const y = top + 34 + index * 42;
      doc.circle(left + 16, y + 6, 3).fill(statusColor(log.action).foreground);
      doc.font('Helvetica-Bold').fontSize(7.8).fillColor('#0f172a').text(trimText(log.action, 24), left + 26, y, {
        width: auditWidth - 38,
        ellipsis: true,
      });
      doc.font('Helvetica').fontSize(7.2).fillColor('#64748b').text(`${log.actor?.name ?? '-'} - ${formatDateTime(log.createdAt)}`, left + 26, y + 12, {
        width: auditWidth - 38,
        ellipsis: true,
      });
    });
  } else {
    doc.font('Helvetica').fontSize(8).fillColor('#64748b').text('-', left + 12, top + 34, { width: auditWidth - 24 });
  }

  const receiptLeft = left + auditWidth + gap;
  drawCard(doc, receiptLeft, top, receiptWidth, blockHeight, '#ffffff', '#e2e8f0');
  doc.font('Helvetica-Bold').fontSize(10).fillColor('#0f172a').text(t.receipt, receiptLeft + 12, top + 10, { width: receiptWidth - 24 });
  const attachment = note.attachments?.[0];
  if (!attachment) {
    doc.font('Helvetica').fontSize(8).fillColor('#64748b').text(t.noReceipt, receiptLeft + 12, top + 34, { width: receiptWidth - 24 });
  } else {
    const filePath = resolveReceiptStorageKey(attachment.storageKey);
    if (attachment.mimeType.startsWith('image/') && fs.existsSync(filePath)) {
      doc.image(filePath, receiptLeft + 12, top + 32, {
        fit: [receiptWidth - 24, 122],
        align: 'center',
        valign: 'center',
      });
    } else {
      doc.font('Helvetica-Bold').fontSize(8.5).fillColor('#334155').text(t.pdfReceipt, receiptLeft + 12, top + 36, { width: receiptWidth - 24 });
      doc.font('Helvetica').fontSize(7.5).fillColor('#64748b').text(trimText(path.basename(attachment.originalName), 52), receiptLeft + 12, top + 54, { width: receiptWidth - 24 });
    }
  }
  doc.y = top + blockHeight + 8;
}

