  doc.font('Helvetica-Bold').fontSize(14).fillColor('#ffffff');
  doc.text(company.name, left + 46, 22, { width: 250, ellipsis: true });
  doc.font('Helvetica').fontSize(7.5).fillColor('#cbd5e1');
  doc.text([company.address, company.phone, company.email].filter(Boolean).join(' | '), left + 46, 42, {
    width: 285,
    ellipsis: true,
  });
  doc.font('Helvetica-Bold').fontSize(20).fillColor('#ffffff');
  doc.text(t.title, left + width - 210, 22, { width: 210, align: 'right' });
  doc.font('Helvetica-Bold').fontSize(9).fillColor('#bfdbfe');
