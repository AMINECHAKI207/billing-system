function drawAudit(doc: PDFKit.PDFDocument, note: ExpensePdfNote, t: ExpensePdfLabels) {
  const logs = (note.auditLogs ?? []).slice(-6);
  if (!logs.length) return;
  ensureSpace(doc, 46 + logs.length * 22);
  const left = pageLeft(doc);
  doc.font('Helvetica-Bold').fontSize(12).fillColor('#0f172a');
  doc.text(t.audit, left, doc.y, { width: pageWidth(doc) });
  doc.y += 16;
  logs.forEach((log) => {
    ensureSpace(doc, 24);
    doc.circle(left + 5, doc.y + 6, 3).fill(statusColor(log.action).foreground);
    doc.font('Helvetica-Bold').fontSize(8.5).fillColor('#0f172a');
    doc.text(log.action, left + 16, doc.y, { width: 165, lineBreak: false });
    doc.font('Helvetica').fillColor('#64748b');
    doc.text(`${log.actor?.name ?? '-'} - ${formatDateTime(log.createdAt)}`, left + 184, doc.y, {
      width: pageWidth(doc) - 184,
      lineBreak: false,
    });
    doc.y += 20;
  });
  doc.y += 4;
}

function drawReceipt(doc: PDFKit.PDFDocument, note: ExpensePdfNote, t: ExpensePdfLabels) {
  const attachment = note.attachments?.[0];
  ensureSpace(doc, 170);
  const left = pageLeft(doc);
  doc.font('Helvetica-Bold').fontSize(12).fillColor('#0f172a');
  doc.text(t.receipt, left, doc.y, { width: pageWidth(doc) });
  doc.y += 18;
  const top = doc.y;
  drawCard(doc, left, top, pageWidth(doc), 150, '#ffffff', '#e2e8f0');
  if (!attachment) {
    doc.font('Helvetica').fontSize(9).fillColor('#64748b').text(t.noReceipt, left + 16, top + 18);
    doc.y = top + 166;
    return;
  }
  const filePath = resolveReceiptStorageKey(attachment.storageKey);
  if (attachment.mimeType.startsWith('image/') && fs.existsSync(filePath)) {
    doc.image(filePath, left + 16, top + 14, { fit: [pageWidth(doc) - 32, 118], align: 'center', valign: 'center' });
  } else {
    const fileName = path.basename(attachment.originalName);
    doc.font('Helvetica-Bold').fontSize(10).fillColor('#334155').text(t.pdfReceipt, left + 16, top + 18);
    doc.font('Helvetica').fontSize(9).fillColor('#64748b').text(fileName, left + 16, top + 38);
  }
  doc.y = top + 166;
}

function drawInfoCard(doc: PDFKit.PDFDocument, x: number, y: number, width: number, height: number, title: string, lines: Array<string | null | undefined>) {
  drawCard(doc, x, y, width, height, '#ffffff', '#dbeafe');
  doc.font('Helvetica-Bold').fontSize(8).fillColor('#2563eb').text(title.toUpperCase(), x + 14, y + 14);
  doc.font('Helvetica-Bold').fontSize(10).fillColor('#0f172a');
  const clean = lines.filter((line): line is string => Boolean(line));
  doc.text(clean[0] ?? '-', x + 14, y + 34, { width: width - 28, ellipsis: true });
  doc.font('Helvetica').fontSize(8.5).fillColor('#475569');
  clean.slice(1).forEach((line, index) => doc.text(line, x + 14, y + 50 + index * 12, { width: width - 28, ellipsis: true }));
}

function drawMeta(doc: PDFKit.PDFDocument, x: number, y: number, label: string, value: string, strong = false) {
  doc.font('Helvetica-Bold').fontSize(7.2).fillColor('#64748b').text(label.toUpperCase(), x, y, { width: 120 });
  doc.font('Helvetica-Bold').fontSize(strong ? 11 : 9.5).fillColor(strong ? '#0f172a' : '#334155').text(value, x, y + 13, {
    width: 118,
    ellipsis: true,
  });
}

function drawCompactMeta(doc: PDFKit.PDFDocument, x: number, y: number, label: string, value: string, strong = false) {
  doc.font('Helvetica-Bold').fontSize(6.8).fillColor('#64748b').text(label.toUpperCase(), x, y, { width: 122 });
  doc.font('Helvetica-Bold').fontSize(strong ? 9.2 : 8.2).fillColor(strong ? '#0f172a' : '#334155').text(value, x, y + 11, {
    width: 120,
    ellipsis: true,
  });
}

function drawBadge(doc: PDFKit.PDFDocument, x: number, y: number, width: number, height: number, label: string, colors: { background: string; foreground: string }) {
  doc.roundedRect(x, y, width, height, height / 2).fill(colors.background);
  doc.font('Helvetica-Bold').fontSize(7.5).fillColor(colors.foreground);
  doc.text(label, x + 8, y + 7, { width: width - 16, align: 'center' });
}

function drawCard(doc: PDFKit.PDFDocument, x: number, y: number, width: number, height: number, fill: string, stroke: string) {
  doc.roundedRect(x, y, width, height, 8).fill(fill);
  doc.strokeColor(stroke).lineWidth(0.8).roundedRect(x, y, width, height, 8).stroke();
}

function drawReportTableHeader(doc: PDFKit.PDFDocument, columns: Array<{ label: string; width: number; align: 'left' | 'right' }>) {
  ensureSpace(doc, 34);
  const left = pageLeft(doc);
  doc.roundedRect(left, doc.y, pageWidth(doc), 24, 6).fill('#2563eb');
  doc.font('Helvetica-Bold').fontSize(7.5).fillColor('#ffffff');
  let x = left;
  columns.forEach((column) => {
    doc.text(column.label, x + 6, doc.y + 8, { width: column.width - 12, align: column.align });
    x += column.width;
  });
  doc.y += 28;
}

function drawReportRow(doc: PDFKit.PDFDocument, columns: Array<{ width: number; align: 'left' | 'right' }>, cells: string[], index: number) {
  ensureSpace(doc, 34);
  const left = pageLeft(doc);
  const top = doc.y;
  doc.roundedRect(left, top, pageWidth(doc), 28, 4).fill(index % 2 === 0 ? '#ffffff' : '#f8fafc');
  doc.strokeColor('#e2e8f0').lineWidth(0.4).roundedRect(left, top, pageWidth(doc), 28, 4).stroke();
  doc.font('Helvetica').fontSize(7.5).fillColor('#334155');
  let x = left;
  cells.forEach((cell, cellIndex) => {
    const column = columns[cellIndex];
    if (!column) return;
    doc.text(cell, x + 6, top + 9, { width: column.width - 12, align: column.align, ellipsis: true });
    x += column.width;
  });
  doc.y += 30;
}

function drawFooters(doc: PDFKit.PDFDocument, company: CompanySettings, generatedBy: { name: string; email: string }, t: ExpensePdfLabels) {
  const range = doc.bufferedPageRange();
  for (let pageIndex = range.start; pageIndex < range.start + range.count; pageIndex += 1) {
    doc.switchToPage(pageIndex);
    const left = pageLeft(doc);
    const y = doc.page.height - doc.page.margins.bottom - 18;
    doc.moveTo(left, y - 10).lineTo(pageRight(doc), y - 10).strokeColor('#e2e8f0').lineWidth(0.6).stroke();
    doc.font('Helvetica').fontSize(7).fillColor('#64748b');
    doc.text(`${t.generatedBy}: ${generatedBy.name} | ${t.generatedAt}: ${formatDateTime(new Date())}`, left, y, { width: 360 });
    doc.text(`${t.page} ${pageIndex - range.start + 1} / ${range.count}`, pageRight(doc) - 90, y, { width: 90, align: 'right' });
    doc.text(company.email ?? company.name, left, y + 10, { width: 280 });
  }
}

function ensureSpace(doc: PDFKit.PDFDocument, requiredHeight: number) {
  if (doc.y + requiredHeight <= doc.page.height - doc.page.margins.bottom - 28) return;
  doc.addPage();
  doc.y = 54;
}

function pageLeft(doc: PDFKit.PDFDocument) {
  return doc.page.margins.left;
}

function pageRight(doc: PDFKit.PDFDocument) {
  return doc.page.width - doc.page.margins.right;
}

function pageWidth(doc: PDFKit.PDFDocument) {
  return pageRight(doc) - pageLeft(doc);
}

function initials(name: string) {
  return name.split(/\s+/).filter(Boolean).slice(0, 2).map((part) => part[0]?.toUpperCase()).join('');
}

function expenseReference(note: ExpensePdfNote) {
  return note.documentNumber || note.receiptNumber || `EXP-${note.id.slice(0, 8).toUpperCase()}`;
}

function statusColor(status: string) {
  const colors: Record<string, { background: string; foreground: string }> = {
    DRAFT: { background: '#f1f5f9', foreground: '#334155' },
    PROCESSING: { background: '#e0f2fe', foreground: '#0369a1' },
    NEEDS_REVIEW: { background: '#fef3c7', foreground: '#b45309' },
    SUBMITTED: { background: '#dbeafe', foreground: '#1d4ed8' },
    CHANGES_REQUESTED: { background: '#ffedd5', foreground: '#c2410c' },
    APPROVED: { background: '#dcfce7', foreground: '#15803d' },
    REJECTED: { background: '#fee2e2', foreground: '#b91c1c' },
    PAID: { background: '#ede9fe', foreground: '#6d28d9' },
  };
  return colors[status] ?? { background: '#f1f5f9', foreground: '#334155' };
}

function formatCurrency(amount: number, currency: string) {
  return new Intl.NumberFormat('fr-MA', { style: 'currency', currency, minimumFractionDigits: 2 }).format(amount);
}

function formatDate(date: Date) {
  return new Intl.DateTimeFormat('fr-MA', { year: 'numeric', month: '2-digit', day: '2-digit' }).format(date);
}

function formatDateTime(date: Date) {
  return new Intl.DateTimeFormat('fr-MA', { year: 'numeric', month: '2-digit', day: '2-digit', hour: '2-digit', minute: '2-digit' }).format(date);
}

function trimText(value: string, length: number) {
  return value.length > length ? `${value.slice(0, Math.max(0, length - 1))}.` : value;
}
